"""Embed measured fisheye/Brown parameters in RTL without a UART cable.
The generated data is a parameter ROM, not a precomputed pixel-coordinate LUT.
Use --identity for initial wiring tests; it does not correct a real lens.
"""
from pathlib import Path
import argparse,json,hashlib
from camera_config import configuration,normalize_calibration
from fixed_map_fast import vector_fixed_map as fixed_map
from tile_budget import tile_budget
from project_profile import BUILD_ID

def render(words):
    if len(words) not in (16,18):raise ValueError('Boot configuration must contain16 or18 words.')
    cases='\n'.join(f"  5'd{i}: data=32'h{v&0xffffffff:08x};" for i,v in enumerate(words))
    return '''// Generated by tools/make_boot_config.py. See board/boot_config.json.
module video_config_boot #(parameter IMG_WIDTH=1280,IMG_HEIGHT=720)(
 input wire clk,rst_n,output wire valid,output wire[4:0] addr,
 output reg[31:0] data,input wire ready,output wire commit,
 input wire commit_ready,output wire boot_done
);
 reg[1:0] state;reg[4:0] index;
 assign valid=rst_n&&state==0;assign addr=index;
 assign commit=rst_n&&state==1;assign boot_done=state==2;
 always @* case(index)
'''+cases+'''
  default:data=0;
 endcase
 always @(posedge clk or negedge rst_n)
 if(!rst_n) begin state<=0;index<=0;end
 else if(state==0&&ready) begin if(index==LAST_REGISTER) state<=1;else index<=index+1'b1;end
 else if(state==1&&commit_ready) state<=2;
endmodule
'''.replace('LAST_REGISTER',str(len(words)-1))


def write_boot_rtl(target, words):
    """Save deterministic ASCII/LF bytes and return the hash of that file.

    Windows text-mode newline translation used to make the metadata hash
    differ from the saved CRLF file. Hashing saved bytes also keeps this
    contract correct if the serialization policy changes in the future.
    """
    target = Path(target)
    target.write_bytes(render(words).encode('ascii'))
    return hashlib.sha256(target.read_bytes()).hexdigest()


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    group=ap.add_mutually_exclusive_group(required=True)
    group.add_argument('--identity',action='store_true')
    group.add_argument('--calibration',type=Path)
    ap.add_argument('--zoom',type=float,default=1.0)
    ap.add_argument('--legacy-brown',action='store_true',help='Generate historical Brown identity instead of the current fisheye contract')
    ap.add_argument('--allow-synthetic',action='store_true',help='Offline testing only; not measured-lens evidence')
    ap.add_argument('--allow-black-border',action='store_true',help='Accept out-of-image mappings; default requires complete coverage')
    a=ap.parse_args(); root=Path(__file__).resolve().parents[1]
    if (root/'rtl/video_config_boot_complete.v').exists():
        raise ValueError('Legacy boot generator cannot write complete 27-word metadata. Keep current C97 boot and use complete_control.py for runtime parameters.')
    if a.identity:
        if a.legacy_brown:
            d={'model':'brown_k1_k2_p1_p2','width':1280,'height':720,'synthetic':True,
               'camera_matrix':[[1024,0,639.5],[0,1024,359.5],[0,0,1]],'distortion':[0,0,0,0],'fixed_k3':0}
        else:
            from fisheye_config import IDENTITY
            d=dict(IDENTITY)
        source='identity: wiring test only'
    else:
        d=normalize_calibration(json.loads(a.calibration.read_text(encoding='utf-8-sig')));source=str(a.calibration.resolve())
        if d.get('synthetic') is not False and not a.allow_synthetic:
            raise ValueError('Use measured calibration with synthetic=false; synthetic/unspecified data needs --allow-synthetic')
    if (d.get('width'),d.get('height'))!=(1280,720):
        raise ValueError('This board image mode is 1280x720. Do not resize calibration implicitly.')
    words=configuration(d,zoom=a.zoom)
    if len(words)==18:
        from fisheye_reference import vector_fixed_map as mapper
    else:mapper=fixed_map
    maps,errors=mapper(1280,720,words)
    invalid=int(((maps>>38)==0).sum())
    if errors: raise ValueError(f'Fixed-point overflow at {errors} pixels')
    budget=tile_budget(maps,1280,720)
    if budget['unsupported_tiles']:
        raise ValueError('Mapping exceeds FPGA tile cache; adjust field of view/rotation before making boot RTL.')
    if invalid and not a.allow_black_border:
        raise ValueError(f'{invalid} pixels map outside the source. Increase --zoom and retry, or explicitly allow borders for debugging.')
    rtl_sha256=write_boot_rtl(root/'rtl/video_config_boot.v',words)
    meta={'source':source,'synthetic':d.get('synthetic',True),'identity':a.identity,'zoom':a.zoom,
          'model':d['model'],'register_count':len(words),'build_id':f'0x{BUILD_ID:08x}' if len(words)==18 else '0x7200001',
          'width':1280,'height':720,'invalid_pixels':invalid,'overflow_pixels':errors,'words':words,'tile_budget':budget,
          'rtl_sha256':rtl_sha256,
          'note':'Re-run prepare_board.py --channel 1, synthesize and regenerate bitstream. No hardware calibration claim.'}
    (root/'board/boot_config.json').write_text(json.dumps(meta,indent=2,ensure_ascii=False),encoding='utf-8')
    print(f'BOOT CONFIG GENERATED: invalid={invalid} overflow={errors}. Rebuild PDS projects and bitstream.')
if __name__=='__main__':main()
